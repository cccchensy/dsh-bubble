/**
 * Build the browser bundle of `dsh-bubble`.
 *
 * The hand-authored browser half (`src/client.template.js`) carries the whole
 * feature except the audio bytes. This script validates `assets/bubble-chime.wav`,
 * inlines it as a data URI, and writes the installable `lib/client.js`.
 *
 * Run: node scripts/build.mjs
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const wavPath = join(root, 'assets', 'bubble-chime.wav');
const templatePath = join(root, 'src', 'client.template.js');
const outPath = join(root, 'lib', 'client.js');
const placeholder = '__BUBBLE_CHIME_DATA_URI__';

/**
 * Parse the RIFF/WAVE chunks the plugin relies on.
 * @param buffer - complete WAV file bytes.
 * @returns the PCM format facts and derived duration.
 */
function inspectWav(buffer) {
  if (buffer.length < 44) throw new Error('WAV is too short');
  if (buffer.toString('ascii', 0, 4) !== 'RIFF') throw new Error('missing RIFF header');
  if (buffer.toString('ascii', 8, 12) !== 'WAVE') throw new Error('missing WAVE form');
  let offset = 12;
  let fmt;
  let dataSize;
  while (offset + 8 <= buffer.length) {
    const id = buffer.toString('ascii', offset, offset + 4);
    const size = buffer.readUInt32LE(offset + 4);
    const body = offset + 8;
    if (id === 'fmt ') {
      fmt = {
        format: buffer.readUInt16LE(body),
        channels: buffer.readUInt16LE(body + 2),
        sampleRate: buffer.readUInt32LE(body + 4),
        bitsPerSample: buffer.readUInt16LE(body + 14),
      };
    } else if (id === 'data') {
      dataSize = size;
    }
    offset = body + size + (size % 2);
  }
  if (fmt === undefined) throw new Error('missing fmt chunk');
  if (dataSize === undefined) throw new Error('missing data chunk');
  if (fmt.format !== 1) throw new Error(`expected PCM format 1, got ${fmt.format}`);
  if (fmt.channels !== 1) throw new Error(`expected mono, got ${fmt.channels} channels`);
  if (fmt.sampleRate !== 44100) throw new Error(`expected 44100 Hz, got ${fmt.sampleRate}`);
  if (fmt.bitsPerSample !== 16) throw new Error(`expected 16-bit, got ${fmt.bitsPerSample}`);
  const duration = dataSize / (fmt.channels * (fmt.bitsPerSample / 8)) / fmt.sampleRate;
  if (duration < 0.9 || duration > 1.2) throw new Error(`expected 0.9-1.2 s, got ${duration.toFixed(3)} s`);
  return { ...fmt, dataSize, duration };
}

const wav = readFileSync(wavPath);
const facts = inspectWav(wav);
const sha256 = createHash('sha256').update(wav).digest('hex');
const dataUri = `data:audio/wav;base64,${wav.toString('base64')}`;

const template = readFileSync(templatePath, 'utf8');
const occurrences = template.split(placeholder).length - 1;
if (occurrences !== 1) {
  throw new Error(`expected exactly one ${placeholder} in the template, found ${occurrences}`);
}
if (template.includes('data:audio/wav;base64,')) {
  throw new Error('the template must not embed audio bytes itself');
}

const banner = [
  '// Generated by scripts/build.mjs — do not edit this file.',
  `// assets/bubble-chime.wav  sha256:${sha256}  ${wav.length} bytes`,
  `// ${facts.sampleRate} Hz, ${facts.bitsPerSample}-bit, ${facts.channels} channel, ${facts.duration.toFixed(3)} s`,
  '',
].join('\n');

const built = banner + template.replace(placeholder, dataUri);
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, built, 'utf8');

console.log(`wav      ${wavPath}`);
console.log(`         ${facts.duration.toFixed(3)} s  ${facts.sampleRate} Hz  ${facts.bitsPerSample}-bit  mono  ${wav.length} bytes`);
console.log(`         sha256 ${sha256}`);
console.log(`built    ${outPath}  ${Buffer.byteLength(built, 'utf8')} bytes`);
